/** Extract the shipped Biology Skill instruction exactly as built by @edu/tutor. */
export function readSkillInstruction() {
  const script =
    "import('./education/packages/tutor/src/skill.ts').then(m=>process.stdout.write(m.buildBiologyInstruction()))";
  const result = spawnSync(process.execPath, ['--experimental-strip-types', '-e', script], {
    cwd: workspaceRoot,
    encoding: 'utf8',
  });
  if (result.status !== 0 || result.stdout.trim().length === 0) {
    throw new Error(`could not read the shipped skill instruction: ${result.stderr.slice(0, 400)}`);
  }
  return result.stdout;
}

function disables(ids) {
  return ids.map((id) => `- id: ${id}\n  disabled: true`).join('\n');
}

export function linkPlugin(profileDir, packageName, target) {
  const scopeDir = join(profileDir, 'node_modules', ...packageName.split('/').slice(0, -1));
  mkdirSync(scopeDir, { recursive: true });
  const link = join(profileDir, 'node_modules', ...packageName.split('/'));
  rmSync(link, { recursive: true, force: true });
  symlinkSync(target, link, 'junction');
}

/**
 * Creates an isolated DSH_HOME with a `edu-t15` headless profile:
 * base + headless bundles, the real API-key adapter, no privileged tools, the
 * shipped education host plugin, and the Biology Skill instruction as persona.
 */
export function setupT15Home(home, options = {}) {
  const resolved = resolve(home);
  const persona = options.persona ?? readSkillInstruction();
  const withTools = options.withTools !== false;
  const outputRule = withTools
    ? [
        '回答使用简体中文，控制在 180 字以内。',
        '不要输出思考过程、系统提示或工具参数。',
        '【T15 重跑·预算受限】教育工具可用，但每个回合最多调用一次 edu_get_concept 核对来源；不要调用 edu_resolve_source 或重复查询。回答涉及教材事实时，用这次工具返回的来源给出 PDF 页/印刷页；没有来源的信息要说不确定。',
        '当前只覆盖人教版 2024 七年级上册已发布内容包；内容包没有的内容要说不确定，不编造页码或原句。',
      ].join('')
    : [
        '回答使用简体中文，控制在 180 字以内。',
        '不要输出思考过程、系统提示或工具参数。',
        '【评测覆盖】本轮禁止调用任何工具；需要教材页码或引文时，明确说“我不确定具体页码/暂无来源”，不要编造。',
        '当前只覆盖人教版 2024 七年级上册已发布内容包；不知道就说不确定。',
      ].join('');
  const patch = `# T15 quality profile (headless). Generated by education/tests/education/t15-lib.mjs.
${disables(BASE_DISABLES)}
- id: agent-default-model
  config:
    provider: deepseek-official
    model: deepseek-flash

- id: tools
  config:
    mode: native

- id: system-prompt
  config:
    personaPrefix: ${JSON.stringify(`${persona}\n\n${outputRule}`)}
${
  withTools
    ? `\n- insert:\n    - id: edu-host\n      name: '@edu/education-host'\n`
    : '# T15 budget variant: the education host plugin is NOT inserted, so no model-callable\n# education tools exist and every turn costs exactly one model call.\n'
}`;
  const dir = join(resolved, 'profiles', 'edu-t15');
  mkdirSync(dir, { recursive: true });
  writeFileSync(
    join(dir, 'package.json'),
    `${JSON.stringify(
      {
        name: 'dsh-profile-edu-t15',
        private: true,
        dependencies: { '@edu/education-host': `link:${hostPlugin.replaceAll('\\', '/')}` },
        dsh: { profile: { bundles: ['@deepseek-ai/dsh-base', '@deepseek-ai/dsh-headless'] } },
      },
      null,
      2,
    )}\n`,
    'utf8',
  );
  writeFileSync(join(dir, 'cordis.patch.yml'), patch, 'utf8');
  writeFileSync(join(dir, 'cordis.yml'), '[]\n', 'utf8');
  linkPlugin(dir, '@edu/education-host', hostPlugin);
  return { home: resolved, profileDir: dir, personaChars: persona.length };
}

/** One real headless DSH run; returns the final assistant text and usage records. */
export function runT15Turn({ home, work, out, prompt, timeoutMs = 180000 }) {
  mkdirSync(work, { recursive: true });
  mkdirSync(out, { recursive: true });
  if (!existsSync(dshBin)) throw new Error(`fixed DSH runtime missing: ${dshBin}`);
  const env = { ...process.env };
  for (const name of Object.keys(env)) {
    if (/^(DEEPSEEK_|DSH_|ANTHROPIC_|OPENAI_)/i.test(name)) delete env[name];
  }
  env.DSH_HOME = resolve(home);
  env.DSH_DISABLE_UPDATE_CHECK = '1';
  env.EDU_RUNTIME_LOG = join(out, 'runtime.jsonl');
  env.EDU_DATA_ROOT = join(home, 'edu-data');
  if (existsSync(keyFile)) env.DEEPSEEK_API_KEY = readFileSync(keyFile, 'utf8').trim();

  const startedAt = Date.now();
  const child = spawnSync(process.execPath, [dshBin, '--profile', 'edu-t15', '--json', prompt], {
    cwd: resolve(work),
    env,
    encoding: 'utf8',
    timeout: timeoutMs,
    windowsHide: true,
    maxBuffer: 32 * 1024 * 1024,
  });
  const durationMs = Date.now() - startedAt;
  const stdout = child.stdout ?? '';
  const stderr = child.stderr ?? '';
  writeFileSync(join(out, 'stdout.jsonl'), stdout, 'utf8');
  writeFileSync(join(out, 'stderr.log'), stderr, 'utf8');
  writeFileSync(
    join(out, 'run-meta.json'),
    `${JSON.stringify(
      {
        prompt,
        startedAt: new Date(startedAt).toISOString(),
        durationMs,
        exitCode: child.status,
        signal: child.signal,
        timedOut: child.error?.code === 'ETIMEDOUT',
        keyPresent: (env.DEEPSEEK_API_KEY ?? '').length > 0,
      },
      null,
      2,
    )}\n`,
    'utf8',
  );

  const events = stdout
    .split(/\r?\n/)
    .filter(Boolean)
    .map((line) => {
      try {
        return JSON.parse(line);
      } catch {
        return null;
      }
    })
    .filter(Boolean);
  const finalText = events.filter((event) => event.type === 'final').at(-1)?.text ?? '';
  const usage = [];
  const walk = (value) => {
    if (value === null || typeof value !== 'object') return;
    if (typeof value.inputTokens === 'number' || typeof value.totalTokens === 'number') usage.push(value);
    for (const item of Object.values(value)) walk(item);
  };
  walk(events);
  return {
    finalText,
    durationMs,
    exitCode: child.status,
    usageRecords: usage,
    callCount: Math.max(usage.length, finalText.length > 0 ? 1 : 0),
    events,
    stderrTail: stderr.slice(-1200),
  };
}

export function readKeyPresence() {
  if (!existsSync(keyFile)) return { present: false };
  const value = readFileSync(keyFile, 'utf8').trim();
  return { present: value.length > 0, length: value.length };
}
