/**
 * T15 harness library (real DSH headless + real education host plugin).
 *
 * Why headless and not the G1 HTTP tutor route: the isolated web host's
 * `/edu/api/g1/tutor/turn` deterministically returned
 * `UNAVAILABLE: DSH turn produced no assistant text` on two independent runs
 * (see evidence/T15/pilot and pilot2). The defect is inside the DSH tutor
 * gateway/T13 surface (not in this harness), so T15 evaluates the shipped tutor
 * instruction + real model + real education tools through the headless profile,
 * which is a real DSH binding of the same education composition.
 *
 * The biological Skill instruction is imported from the shipped source with
 * Node's type stripping and used as the profile persona, because the G1 gateway
 * adapter drops `TutorPrompt.systemInstruction` (see report finding T15-F1).
 */
