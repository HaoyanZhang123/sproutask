function linkPlugin(profileDir, packageName, target) {
  const scopeDir = path.join(profileDir, 'node_modules', ...packageName.split('/').slice(0, -1));
  mkdirSync(scopeDir, { recursive: true });
  const link = path.join(profileDir, 'node_modules', ...packageName.split('/'));
  rmSync(link, { recursive: true, force: true });
  symlinkSync(target, link, 'junction');
}

function writeProfile(home, name, bundles, dependencies, patch) {
  const dir = path.join(home, 'profiles', name);
  mkdirSync(dir, { recursive: true });
  writeFileSync(
    path.join(dir, 'package.json'),
    `${JSON.stringify(
      {
        name: `dsh-profile-${name}`,
        private: true,
        dependencies,
        dsh: { profile: { bundles } },
      },
      null,
      2,
    )}\n`,
    'utf8',
  );
  writeFileSync(path.join(dir, 'cordis.patch.yml'), patch, 'utf8');
  writeFileSync(path.join(dir, 'cordis.yml'), '[]\n', 'utf8');
  return dir;
}

export function setupEducationHome(home) {
  const resolved = path.resolve(home);
  mkdirSync(resolved, { recursive: true });
  const hostDep = { '@edu/education-host': `link:${hostPlugin.replaceAll('\\', '/')}` };
  const web = writeProfile(
    resolved,
    'edu-web',
    ['@deepseek-ai/dsh-base', '@deepseek-ai/dsh-web-app'],
    {
      ...hostDep,
      '@edu/client-root': `link:${clientPlugin.replaceAll('\\', '/')}`,
    },
    patchFor(true),
  );
  const headless = writeProfile(
    resolved,
    'edu-headless',
    ['@deepseek-ai/dsh-base', '@deepseek-ai/dsh-headless'],
    hostDep,
    patchFor(false),
  );
  linkPlugin(web, '@edu/education-host', hostPlugin);
  linkPlugin(web, '@edu/client-root', clientPlugin);
  linkPlugin(headless, '@edu/education-host', hostPlugin);
  return { home: resolved, profiles: { web, headless } };
}

/**
 * 是否被直接执行（而不是被 import）。
 *
 * 安装目录可能是 junction / 符号链接（联调根、便携部署），也可能带 8.3 短名；
 * 直接比较 argv[1] 与 import.meta.url 会不等，脚本静默 no-op。这里比较 realpath。
 */
function isDirectInvocation() {
  if (process.argv[1] === undefined) return false;
  try {
    return (
      realpathSync(path.resolve(process.argv[1])) === realpathSync(fileURLToPath(import.meta.url))
    );
  } catch {
    return path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
  }
}

if (isDirectInvocation()) {
  const args = parseArgs();
  if (typeof args.home !== 'string' || !path.isAbsolute(args.home)) {
    console.error('usage: node scripts/setup-education-home.mjs --home <absolute DSH_HOME>');
    process.exit(2);
  }
  if (!existsSync(path.join(hostPlugin, 'lib', 'index.js'))) {
    console.error('host plugin is not built; run: pnpm --dir education build');
    process.exit(3);
  }
  if (!existsSync(path.join(clientPlugin, 'lib', 'client.js'))) {
    console.error('client plugin is not built; run: pnpm --dir education build');
    process.exit(3);
  }
  console.log(JSON.stringify(setupEducationHome(args.home), null, 2));
}
