/**
 * Generates an isolated DSH_HOME for the education runtime (web + headless).
 *
 * The profile keeps the fixed @deepseek-ai/dsh-base + web/headless bundles,
 * keeps the real API-key model adapter, removes the default layout-dependent
 * client rows (runtime-lock constraint: 23 pending rows when ui-layout is
 * removed), and links the two local plugin packages into the profile's
 * node_modules. It never touches E:\DSH\.dsh or the current GUI profile.
 */

