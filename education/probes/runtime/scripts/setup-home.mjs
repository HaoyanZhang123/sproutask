function writeProfile(name, bundles, dependencies, patch) {
  const dir = join(home, 'profiles', name);
  mkdirSync(dir, { recursive: true });
  const pkg = {
    name: `dsh-profile-${name}`,
    private: true,
    dependencies,
    dsh: { profile: { bundles } },
  };
  writeFileSync(join(dir, 'package.json'), `${JSON.stringify(pkg, null, 2)}\n`, 'utf8');
  writeFileSync(join(dir, 'cordis.patch.yml'), patch, 'utf8');
  writeFileSync(join(dir, 'cordis.yml'), '[]\n', 'utf8');
  writeFileSync(
    join(dir, 'pnpm-workspace.yaml'),
    'packages:\n  - .\n\nnodeLinker: hoisted\nautoInstallPeers: false\n',
    'utf8',
  );
  return dir;
}

